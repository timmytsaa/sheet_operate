def person_name(rng: Random) -> str:
    return rng.choice(SURNAMES) + rng.choice(GIVEN_NAMES)


def split_person_name(rng: Random) -> tuple[str, str]:
    """回傳 (姓, 名)。"""
    return rng.choice(SURNAMES), rng.choice(GIVEN_NAMES)


def city(rng: Random) -> str:
    return rng.choice(CITIES)


def pick_cities(rng: Random, k: int) -> list[str]:
    return rng.sample(CITIES, k)


def product(rng: Random) -> tuple[str, str, int]:
    """回傳 (產品名, 類別, 單價)。單價為區間內 10 的倍數。"""
    name, cat, lo, hi = rng.choice(PRODUCTS)
    price = rng.randrange(lo // 10, hi // 10 + 1) * 10
    return name, cat, price


def order_id(i: int) -> str:
    return f"TW{1000 + i}"


def order_date(rng: Random, year: int = 2026) -> _dt.date:
    return _dt.date(year, rng.randint(1, 7), rng.randint(1, 28))
